/**
  * @brief  The application entry point.
  * @retval int
  */
int main(void)
{

  /* USER CODE BEGIN 1 */
  char key;
  uint32_t standby_tick = 0U;

  /* USER CODE END 1 */

  /* MCU Configuration--------------------------------------------------------*/

  /* Reset of all peripherals, Initializes the Flash interface and the Systick. */
  HAL_Init();

  /* USER CODE BEGIN Init */

  /* USER CODE END Init */

  /* Configure the system clock */
  SystemClock_Config();

  /* USER CODE BEGIN SysInit */

  /* USER CODE END SysInit */

  /* Initialize all configured peripherals */
  MX_GPIO_Init();
  MX_DMA_Init();
  MX_ADC1_Init();
  MX_TIM5_Init();
  MX_SPI2_Init();
  MX_TIM8_Init();
  /* USER CODE BEGIN 2 */

  OLED_Init();
  Keyboard_Init();

  /* 先校准并就绪 ADC DMA，再启动 TIM8 触发和调制，保持输出关闭。 */
  if (INV_SamplingStart() != HAL_OK) Error_Handler();
  if (INV_Init() != HAL_OK) Error_Handler();

  /* 欢迎界面（替代原工程 gImage_welcome 开机图） */
  OLED_Clear();
  OLED_ShowString(16, 8,  "INVERTER", 16);
  OLED_ShowString(16, 32, "G474 PORT", 16);
  OLED_Refresh();
  HAL_Delay(2000);

  INV_ShowStandby();
  standby_tick = HAL_GetTick();

  /* USER CODE END 2 */

  /* Infinite loop */
  /* USER CODE BEGIN WHILE */
  while (1)
  {
    /* USER CODE END WHILE */

    /* USER CODE BEGIN 3 */
    key = Keyboard_GetKey();
    if (key == 'A')                 /* 功率输出开关 */
    {
      if (INV_PwmFlag) INV_OutputDisable();
      else             INV_OutputEnable();
      INV_ShowStandby();
      standby_tick = HAL_GetTick();
    }
    else if (key == 'C')
    {
      INV_OutputDisable();
      INV_ShowStandby();
    }
    else if (key == 'D')            /* 进入参数菜单 */
    {
      INV_Menu_Run();
      INV_ShowStandby();
      standby_tick = HAL_GetTick();
    }

    /* 定时刷新输出命令和频率、幅度。 */
    if (HAL_GetTick() - standby_tick >= 200U)
    {
      standby_tick = HAL_GetTick();
      INV_ShowStandby();
    }
  }
  /* USER CODE END 3 */
}

